"""Tests for the Nov 24 review, Track B (items 6-11): codemap generator hardening.

stdlib unittest; no network. Fake secrets are assembled at runtime so this file never
contains a key-shaped literal.

B6  private names are detected and fail --verify-docs / --check; they never rewrite output,
    so generated bytes are identical whether or not the local private-names file exists.
B7  the generator runs only on the pinned Python (the CI version); README and CI agree.
B8  the scrubber also redacts Google API keys, GitLab PATs, JWTs and Slack webhook URLs.
B9  verify_docs resolves local `codemap/...` references against `git ls-files` only.
B10 the weekly staleness job fails when a pin is behind (or upstream is unreadable).
B11 Hermes dashboard plugin routes are mapped as /api/plugins/<name>/<route>, without
    picking up every route decorator or bare relative path in the stack.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import build  # noqa: E402

FAKE_NAME = "examplehost-alpha"  # stands in for a private machine name


def _cat(*parts: str) -> str:
    """Join at runtime: `+` on literals is constant-folded into the .pyc, which secret scanners then flag."""
    return "".join(parts)


def _git(cwd, *args):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def _fake_root(td: Path, tracked: dict, untracked: dict | None = None) -> Path:
    """A minimal rizzstack-shaped git repo: sources.json with no repos, plus the given files."""
    (td / "scripts" / "codemap").mkdir(parents=True)
    (td / "codemap" / "generated").mkdir(parents=True)
    (td / "scripts" / "codemap" / "sources.json").write_text(json.dumps({"repos": []}))
    for rel, text in tracked.items():
        (td / rel).parent.mkdir(parents=True, exist_ok=True)
        (td / rel).write_text(text)
    _git(td, "init", "-q")
    _git(td, "add", "-A")
    _git(td, "-c", "user.email=t@example.invalid", "-c", "user.name=t", "commit", "-qm", "fixture")
    for rel, text in (untracked or {}).items():
        (td / rel).parent.mkdir(parents=True, exist_ok=True)
        (td / rel).write_text(text)
    return td


def _patched(root: Path):
    return mock.patch.multiple(build, ROOT=root, OUT=root / "codemap" / "generated",
                               SOURCES=root / "scripts" / "codemap" / "sources.json")


def _tiny_repo(td: Path) -> Path:
    p = td / "repo"
    (p / "pkg").mkdir(parents=True)
    (p / "pkg" / "__init__.py").write_text('"""Pkg doc."""\n')
    (p / "pkg" / "core.py").write_text(f'"""Talks to {FAKE_NAME}."""\nHOST_NAME = "{FAKE_NAME}"\ndef helper():\n    return 1\n')
    (p / "pkg" / "use.py").write_text("from .core import helper\nURL = '/v1/things'\nhelper()\n")
    _git(p, "init", "-q")
    _git(p, "add", "-A")
    _git(p, "-c", "user.email=t@example.invalid", "-c", "user.name=t", "commit", "-qm", "x")
    return p


def _render(repo: Path) -> tuple[bytes, bytes]:
    ix = build.index_repo({"name": "t", "url": "u", "sha": "0" * 40, "layer": 1, "role": "r"}, repo, [])
    with tempfile.TemporaryDirectory() as out:
        jp = Path(out) / "t.json"
        build.dump_json(jp, ix)
        return jp.read_bytes(), build.render_repo_md(ix).encode()


