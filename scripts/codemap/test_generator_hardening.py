class PythonPinTests(unittest.TestCase):
    def test_pin_matches_ci_and_readme(self):
        wf = (ROOT / ".github" / "workflows" / "codemap.yml").read_text()
        ci = set(re.findall(r'python-version:\s*"([\d.]+)"', wf))
        self.assertEqual(ci, {build.REQUIRED_PYTHON}, "every codemap CI job must use build.REQUIRED_PYTHON")
        readme = (HERE / "README.md").read_text()
        self.assertIn(f"Python {build.REQUIRED_PYTHON}", readme)
        self.assertNotIn("3.11+", readme)

    def test_mismatch_detection(self):
        major, minor = (int(x) for x in build.REQUIRED_PYTHON.split("."))
        self.assertIsNone(build.python_mismatch((major, minor)))
        self.assertIsNotNone(build.python_mismatch((major, minor - 1)))
        self.assertIsNotNone(build.python_mismatch((major, minor + 1)))

    def test_generate_and_check_refuse_other_versions(self):
        with mock.patch.object(build, "runtime_python", return_value=(3, 0)), \
                mock.patch.object(build, "generate", side_effect=AssertionError("must not generate")):
            self.assertEqual(build.main(["--check"]), 2)
            self.assertEqual(build.main([]), 2)

    def test_read_only_modes_still_run_elsewhere(self):
        with mock.patch.object(build, "runtime_python", return_value=(3, 0)):
            with mock.patch.object(build, "budget_report", return_value="ok"):
                self.assertEqual(build.main(["--budgets"]), 0)


