class PluginRouteTests(unittest.TestCase):
    def test_dashboard_plugin_routes_are_mapped_under_api_plugins(self):
        with tempfile.TemporaryDirectory() as td:
            p = Path(td)
            (p / "dashboard").mkdir()
            (p / "dashboard" / "manifest.json").write_text('{"name": "demo", "api": "plugin_api.py"}\n')
            (p / "dashboard" / "plugin_api.py").write_text(
                "from fastapi import APIRouter\nrouter = APIRouter()\n"
                "@router.get('/surfaces/{surface_id}')\ndef s(surface_id): ...\n"
                "@router.post(\"/actions\")\ndef a(): ...\n"
                "def mount():\n    @router.get('/audit')\n    def au(): ...\n")
            (p / "server.py").write_text("@app.get('/health')\ndef h(): ...\nX = '/actions'\n")
            (p / "card.js").write_text("restJson(ctx, '/actions')\n")
            _git(p, "init", "-q")
            _git(p, "add", "-A")
            _git(p, "-c", "user.email=t@example.invalid", "-c", "user.name=t", "commit", "-qm", "x")
            ix = build.index_repo({"name": "t", "url": "u", "sha": "0" * 40, "layer": 1, "role": "r"}, p, [])
        hp = ix["http_paths"]
        for route in ("/api/plugins/demo/actions", "/api/plugins/demo/audit", "/api/plugins/demo/surfaces/{surface_id}"):
            self.assertEqual(hp.get(route), ["dashboard/plugin_api.py"], hp)
        for noise in ("/actions", "/health", "/audit"):
            self.assertNotIn(noise, hp)


