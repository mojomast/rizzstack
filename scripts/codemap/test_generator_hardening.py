class PrivateNamesTests(unittest.TestCase):
    def test_env_var_no_longer_rewrites_output(self):
        env = dict(os.environ, CODEMAP_PRIVATE_NAMES=FAKE_NAME)
        r = subprocess.run([sys.executable, "-c", f"import build; print(build.scrub({FAKE_NAME!r}))"],
                           cwd=HERE, env=env, capture_output=True, text=True, timeout=60)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(r.stdout.strip(), FAKE_NAME, "scrub() must not depend on machine-local private names")

    def test_generated_bytes_identical_with_or_without_private_file(self):
        with tempfile.TemporaryDirectory() as td:
            td = Path(td)
            repo = _tiny_repo(td)
            root = _fake_root(td / "root", {"README.md": "x\n"})
            with _patched(root):
                without = _render(repo)
                (root / "scripts" / "codemap" / "private-names.local").write_text(f"# local only\n{FAKE_NAME}\n")
                with_file = _render(repo)
            self.assertEqual(without, with_file)
            self.assertIn(FAKE_NAME.encode(), with_file[0], "output is not rewritten; detection happens in --verify-docs")

    def test_private_name_in_tracked_file_fails_verify_docs(self):
        with tempfile.TemporaryDirectory() as td:
            root = _fake_root(Path(td), {"codemap/notes.md": f"runs on {FAKE_NAME}\n",
                                         "codemap/generated/x.json": '{"host":"%s"}\n' % FAKE_NAME})
            (root / "scripts" / "codemap" / "private-names.local").write_text(f"# one regex per line\n{FAKE_NAME}\n")
            with _patched(root):
                probs = build.verify_docs()
        hits = [p for p in probs if "private name" in p]
        self.assertTrue(any(p.startswith("codemap/notes.md:1:") for p in hits), probs)
        self.assertTrue(any(p.startswith("codemap/generated/x.json:1:") for p in hits), probs)
        self.assertFalse(any(FAKE_NAME in p for p in probs), "problem text must not echo the private name")

    def test_no_private_file_means_no_private_findings(self):
        with tempfile.TemporaryDirectory() as td:
            root = _fake_root(Path(td), {"codemap/notes.md": f"runs on {FAKE_NAME}\n"})
            with _patched(root), mock.patch.dict(os.environ, {}, clear=False):
                os.environ.pop("CODEMAP_PRIVATE_NAMES", None)
                os.environ.pop("CODEMAP_PRIVATE_NAMES_FILE", None)
                probs = build.verify_docs()
        self.assertEqual([p for p in probs if "private name" in p], [])

    def test_invalid_pattern_is_a_problem_not_a_crash(self):
        with tempfile.TemporaryDirectory() as td:
            root = _fake_root(Path(td), {"codemap/notes.md": "ok\n"})
            (root / "scripts" / "codemap" / "private-names.local").write_text("bad(regex\n")
            with _patched(root):
                probs = build.verify_docs()
        self.assertTrue(any("private-names" in p and "line 1" in p for p in probs), probs)

    def test_private_names_file_is_gitignored(self):
        r = subprocess.run(["git", "check-ignore", "-q", "scripts/codemap/private-names.local"], cwd=ROOT)
        self.assertEqual(r.returncode, 0, "scripts/codemap/private-names.local must be gitignored")


