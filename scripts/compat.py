#!/usr/bin/env python3
"""Generate and check COMPAT.md from compat/tuple.json (stdlib only).

  python3 scripts/compat.py render            # print COMPAT.md
  python3 scripts/compat.py check             # COMPAT.md must equal the rendering
  python3 scripts/compat.py check-pins FILE   # FILE (bundlebees pins.py) must match the recorded pins
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TUPLE = ROOT / "compat" / "tuple.json"
COMPAT = ROOT / "COMPAT.md"
PIN_NAMES = ("WORKFLOW_PIN", "HYVV_PIN", "LAUNCHER_PIN")
#: pin name -> (released repo it should name, field of that repo it is compared with)
PIN_TARGET = {"WORKFLOW_PIN": ("workflow", "sha"), "HYVV_PIN": ("hyvv", "sha"), "LAUNCHER_PIN": ("hyvv", "version")}


def parse_pins(text: str) -> dict[str, str]:
    """The three pins from a pins.py source; a missing pin is an error, never a default."""
    found = dict(re.findall(r'^(\w+_PIN)\s*=\s*"([^"]+)"', text, re.MULTILINE))
    missing = [n for n in PIN_NAMES if n not in found]
    if missing:
        raise ValueError(f"pins.py lacks {', '.join(missing)}")
    return {n: found[n] for n in PIN_NAMES}


def check_pins(tuple_: dict, pins_text: str) -> list[str]:
    """Names of recorded pins that differ from pins_text (empty when they agree)."""
    actual = parse_pins(pins_text)
    recorded = tuple_["bundlebees_pins"]["pins"]
    return [n for n in PIN_NAMES if recorded.get(n) != actual[n]]


def _short(value: str) -> str:
    return value[:12] if re.fullmatch(r"[0-9a-f]{40}", value) else value


def _skew(name: str, value: str, released: dict[str, dict]) -> str:
    repo, field = PIN_TARGET[name]
    want = released.get(repo, {}).get(field)
    if want == value:
        return f"= released {repo} {released[repo]['tag']}"
    what = "commit" if field == "sha" else "version"
    return f"**not the released {repo} {what}** ({released[repo]['tag']} is `{_short(want or '?')}`)"


def render(tuple_: dict) -> str:
    released = {r["repo"]: r for r in tuple_["released"]}
    pins = tuple_["bundlebees_pins"]
    lines = [
        "# COMPAT: released rizzstack tuple",
        "",
        "<!-- Generated by scripts/compat.py from compat/tuple.json. Do not edit by hand. -->",
        "",
        f"As of {tuple_['as_of']}. Tags go out in the order in [docs/RELEASING.md](docs/RELEASING.md).",
        "",
        "| Repo | Version | Tag | Commit | Note |",
        "|---|---|---|---|---|",
    ]
    for r in tuple_["released"]:
        lines.append(f"| {r['repo']} | {r['version']} | `{r['tag']}` | `{r['sha']}` | {r.get('note', '')} |")
    lines += [
        "",
        f"## Pins shipped in {pins['repo']} {pins['tag']} (`{pins['path']}`)",
        "",
        "The pins name the revisions the coordinator's doctor expects on the deployed host,",
        "so they can trail the released tuple. Any skew is listed here rather than hidden.",
        "",
        "| Pin | Value | Against the released tuple |",
        "|---|---|---|",
    ]
    for name in PIN_NAMES:
        value = pins["pins"][name]
        lines.append(f"| {name} | `{_short(value)}` | {_skew(name, value, released)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    tuple_ = json.loads(TUPLE.read_text(encoding="utf-8"))
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "render":
        sys.stdout.write(render(tuple_))
        return 0
    if cmd == "check":
        if COMPAT.read_text(encoding="utf-8") != render(tuple_):
            print("COMPAT.md is stale: run `python3 scripts/compat.py render > COMPAT.md`")
            return 1
        print("COMPAT.md matches compat/tuple.json")
        return 0
    if cmd == "check-pins" and len(argv) == 3:
        drift = check_pins(tuple_, Path(argv[2]).read_text(encoding="utf-8"))
        if drift:
            print(f"bundlebees pins differ from compat/tuple.json: {', '.join(drift)}")
            return 1
        print("bundlebees pins match compat/tuple.json")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
